/* PS5 Cooling & System Center - Pro: opening a save of the console (savemnt.h, 19.11.2026).
 *
 * A save is one encrypted file system image (sdimg_<slot>). To carry it to another console its files have to be read in the clear, and to bring it in, a new
 * image has to be made and filled. Both go through the console's own functions: nothing is decrypted by this app itself.
 *
 *   key     the image carries its key sealed to THIS console (96 bytes at offset 0x800). The kernel's pfsmgr unseals it (ioctl 0xc0845302 on /dev/pfsmgr:
 *           a 0x100-byte buffer on the heap, the sealed bytes first, the 32-byte key comes back at offset 0x60). That is why a raw copy of a save is of no use
 *           on another console: its sealed key can only be opened by the console that made it.
 *   mount   libSceFsInternalForVsh: sceFsInitMountSaveDataOpt / sceFsMountSaveData(opt, image, mount point, key) with budget "system"; sceFsUmountSaveData.
 *           The image is never opened where the console keeps it (that ends in EPIPE): a copy under /data is mounted.
 *   param   a PS5 save keeps its real param.sfo not in the file system (there it is a block of zeros) but in a blob in the image header (offset 0xC00), which
 *           the kernel hands out decrypted through /dev/pfsctldev: 'PS5PARAM' u64, version u32 (0), SFO size u32, SFO offset u32 (20), then the SFO.
 *
 * All of it needs the identity of the save-data service (authid 0x4800000000000010). That identity is the process's, not a thread's: the fan control is on
 * another thread of this process and would lose its own meanwhile. So the whole time between savemnt_open and savemnt_close the Sony lock is held (the fan loop
 * only ever tries it, ps5tm_sony_api_trylock, and waits), and savemnt_close gives the fan's identity back - the same way the tile install does (tile.c).
 *
 * Under PS5TM_HOST_TEST nothing of this touches a kernel: a "mount" is a folder the test has filled, and the param blob is read from "<image>.param". */
#ifndef PS5TM_SAVEMNT_H
#define PS5TM_SAVEMNT_H

#include <stddef.h>
#include <stdint.h>

#define SAVEMNT_SEALED_OFFSET 0x800u
#define SAVEMNT_SEALED_BYTES  96u
#define SAVEMNT_PARAM_OFFSET  0xC00u
#define SAVEMNT_PARAM_BYTES   0x8000u
#define SAVEMNT_PARAM_MAGIC   UINT64_C(0x4D41524150355350)       /* "PS5PARAM" read as a little-endian number */

typedef struct {
  int  open;                    /* 1 between a successful savemnt_open and savemnt_close */
  int  handle;                  /* what sceFsMountSaveData returned */
  char image[320];
  char mount[256];
} savemnt_t;

/* The identity and the lock are taken here and held until savemnt_close. image: the copy under /data (PS5 image, byte 0 is 2); mount_dir: an empty folder.
   0 on success; else -1 with a German sentence in err (nothing is held then). */
int savemnt_open(const char *image, const char *mount_dir, savemnt_t *m, char *err, size_t err_len);

/* The same for a PS4 save: its image has no sealed key inside; the 96 bytes sit in the companion file <slot>.bin beside it (the caller reads them). */
int savemnt_open_sealed(const char *image, const uint8_t sealed[96], const char *mount_dir, savemnt_t *m, char *err, size_t err_len);

/* A new, empty PS4 save image at path of `size` bytes (a multiple of 32768), formatted by the console's own formatter with a fresh key: that key is generated by the
   console, sealed to it, and handed back in sealed_out (96 bytes: they belong into <slot>.bin beside the image). The identity and the lock are taken for this call alone.
   0 or -1 (err says why; nothing is left behind). */
int savemnt_create_ps4(const char *path, uint64_t size, uint8_t sealed_out[96], char *err, size_t err_len);

/* The kind of image the first 0x40 bytes show: 1 a PS4 save, 2 a PS5 save, 0 neither. */
int savemnt_header_kind(const uint8_t *header, size_t len);

/* Unmounts (the image is written back by the console), gives the identity back and releases the lock. 0 when the unmount went well, else -1 (err says why); the
   identity and the lock are given back in every case. Safe on a handle that is not open. */
int savemnt_close(savemnt_t *m, char *err, size_t err_len);

/* A new, empty PS5 save image at path (a file that must not exist yet) of `size` bytes with blocks of block_size (32768 or 65536), made by the console's own
   formatter, in the layout of the images this app reads out (the one the firmware of this console writes with a real param.sfo in the file system). The
   identity and the lock are taken for this call alone; the image is then opened with savemnt_open. 0 or -1 (err says why; nothing is left behind). */
int savemnt_create(const char *path, uint64_t size, uint32_t block_size, char *err, size_t err_len);

/* Unmounts whatever is mounted on mount_dir: a leftover of a run that was cut off (the console keeps a mount until it is told to let go). The identity and the
   lock are taken for this call alone. 0 when the console let go, else -1 (err says why). Never call it on a folder that holds files of its own. */
int savemnt_umount_path(const char *mount_dir, char *err, size_t err_len);

/* The real param.sfo of the image (see "param" above); the identity of the service is needed: call between savemnt_open and savemnt_close, or with
   elevated = 0 to take it for this call alone. *sfo_len gets its size. 0 on success (the SFO is then valid-looking: "\0PSF"), -1 when the image has no such blob
   (a save whose file system holds a real param.sfo), -2 on an error (err says why). */
int savemnt_param_read(const char *image, int already_elevated, uint8_t *sfo, uint32_t sfo_cap, uint32_t *sfo_len, char *err, size_t err_len);

/* The first 0x40 bytes of the superblock tell the kind of image: 2 for PS5 (1 is a PS4 save), and the PFS magic 20130315 at offset 8. 1 when it is a PS5 image. */
int savemnt_is_ps5_header(const uint8_t *header, size_t len);

#endif
