#!/usr/bin/env python3
"""Embeds the APR-EMU versions of third_party/ampr_emu, the PlayGo stubs of third_party/playgo or the DLC modules of third_party/dlc_emu
into a C source file (12.10.2026, dlc 13.10.2026).

Usage: gen_emu_blob.py <output.c> <folder> [ampr|playgo|dlc]

The third argument picks the library: "ampr" (default) is libSceAmpr.sprx of third_party/ampr_emu, table ps5tm_emu_blobs;
"playgo" is libScePlayGo.sprx of third_party/playgo (drakmor's pgo_stub), table ps5tm_playgo_blobs; "dlc" are libSceAppContent.sprx,
libSceGameUpdate.sprx and libSceNpEntitlementAccess.sprx of third_party/dlc_emu (drakmor's dlc_emu), table ps5tm_dlc_blobs.

Every file named <library>.sprx-<version>-<variant> in the folder is stored zlib-compressed (about 42 % of its size) with its
name, its size and its SHA-256, in the table that src/amprlib.c reads. The app unpacks a version only when the person puts it
into the store folder (AMPR_EMU, PlayGo) or builds it into a game; the SHA-256 is checked then, and again here: a file that is
not a build of the project (SELF header 4F 15 3D 1D and the mark "[AMPR_EMU]" / "playgo_stub.dat") stops the build.

The files are GPL-3.0 binaries of https://github.com/drakmor/ampr_emu and https://github.com/drakmor/pgo_stub (the ORIGIN.md
in each folder says which, and how they were checked). Only a few versions are embedded on purpose: a payload of about 10 MB
is where a console stopped loading the app on 02.10.2026 (docs/ENTWICKLUNG.md), and the embedded files add their compressed
size to it.
"""
import hashlib
import os
import re
import sys
import zlib

# prefix of the file names, mark inside every build, table, count, what it is called in messages, C symbol prefix, folder name
KINDS = {
    "ampr":   ("libSceAmpr.sprx-",   b"[AMPR_EMU]",      "ps5tm_emu_blobs",    "ps5tm_emu_blob_count",    "APR-EMU",     "emu",    "third_party/ampr_emu"),
    "playgo": ("libScePlayGo.sprx-", b"playgo_stub.dat", "ps5tm_playgo_blobs", "ps5tm_playgo_blob_count", "PlayGo-Stub", "playgo", "third_party/playgo"),
    # three libraries, so the prefix is a tuple: every name is <library>.sprx-<version>-<variant>
    "dlc":    (("libSceAppContent.sprx-", "libSceGameUpdate.sprx-", "libSceNpEntitlementAccess.sprx-"), b"dlc_emu", "ps5tm_dlc_blobs",
               "ps5tm_dlc_blob_count", "DLC-Modul", "dlc", "third_party/dlc_emu"),
}


def main():
    if len(sys.argv) not in (3, 4) or (len(sys.argv) == 4 and sys.argv[3] not in KINDS):
        sys.exit("usage: gen_emu_blob.py <output.c> <folder> [ampr|playgo|dlc]")
    out_path, folder = sys.argv[1], sys.argv[2]
    prefix, mark, table_name, count_name, what, sym, src_dir = KINDS[sys.argv[3] if len(sys.argv) == 4 else "ampr"]
    prefixes = prefix if isinstance(prefix, tuple) else (prefix,)
    name_re = re.compile("^(" + "|".join(re.escape(x) for x in prefixes) + r")\d+(\.\d+)*(-[A-Za-z0-9._-]+)?$")
    names = sorted(n for n in os.listdir(folder) if n.startswith(prefixes))
    if not names:
        sys.exit("gen_emu_blob: keine Dateien %s* in %s" % (prefixes[0], folder))
    lines = ["/* generated by tools/gen_emu_blob.py: the %s versions of %s, zlib-compressed */" % (what, src_dir),
             '#include "ps5tm.h"', ""]
    table = []
    total = packed_total = 0
    for i, n in enumerate(names):
        if not name_re.match(n):
            sys.exit("gen_emu_blob: der Name %s passt nicht zu %s<Version>-<Variante>" % (n, prefixes[0]))
        data = open(os.path.join(folder, n), "rb").read()
        if len(data) < 0x100 or data[:4] != b"\x4f\x15\x3d\x1d" or mark not in data:
            sys.exit("gen_emu_blob: %s ist keine %s-Datei (SELF-Kopf und %s fehlen)" % (n, what, mark.decode()))
        z = zlib.compress(data, 9)
        if zlib.decompress(z) != data:
            sys.exit("gen_emu_blob: %s lässt sich nicht verlustfrei packen" % n)
        sha = hashlib.sha256(data).hexdigest()
        total += len(data)
        packed_total += len(z)
        lines.append("static const unsigned char %s_%d[] = {" % (sym, i))
        for k in range(0, len(z), 24):
            lines.append("  " + ",".join("0x%02x" % b for b in z[k:k + 24]) + ",")
        lines.append("};")
        table.append('  { "%s", %d, "%s", %s_%d, %d },' % (n, len(data), sha, sym, i, len(z)))
    lines.append("")
    lines.append("const ps5tm_emu_blob_t %s[] = {" % table_name)
    lines += table
    lines.append("};")
    lines.append("const unsigned %s = %d;" % (count_name, len(names)))
    tmp = out_path + ".tmp"
    with open(tmp, "w", newline="\n") as f:
        f.write("\n".join(lines) + "\n")
    os.replace(tmp, out_path)
    print("gen_emu_blob: %d %s-Dateien eingebettet (%d KiB, gepackt %d KiB) -> %s" % (len(names), what, total // 1024, packed_total // 1024, out_path))


if __name__ == "__main__":
    main()
