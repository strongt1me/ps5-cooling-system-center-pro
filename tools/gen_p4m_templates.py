#!/usr/bin/env python3
"""Writes gen/pdb_template.h: the three PlayGo record layouts of PS4Mount (third_party/ps4mount/*.bin) as C arrays.
Usage: gen_p4m_templates.py <out.h>"""
import os, sys
HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, "..", "third_party", "ps4mount")
NAMES = [("k_pdb_template", "pdb_app_template.bin"), ("k_pdb_patch_template", "pdb_patch_template.bin"),
         ("k_pdb_addcont_template", "pdb_addcont_template.bin")]
out = ["/* generated by tools/gen_p4m_templates.py - do not edit */"]
for name, f in NAMES:
    d = open(os.path.join(SRC, f), "rb").read()
    out.append("static const unsigned char %s[] = {" % name)
    for i in range(0, len(d), 12):
        out.append("  " + ", ".join("0x%02x" % b for b in d[i:i + 12]) + ",")
    out.append("};")
os.makedirs(os.path.dirname(os.path.abspath(sys.argv[1])), exist_ok=True)
open(sys.argv[1], "w", newline="\n").write("\n".join(out) + "\n")
