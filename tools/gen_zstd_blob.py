#!/usr/bin/env python3
"""Embeds a program that is already stored as a zstd frame (a .zst file) into a C source file.

Usage: gen_zstd_blob.py <output.c> <file.elf.zst> <symbol>

Dump Forge (src/dumpforge.c, 21.11.2026) is 17.7 MiB; as a zstd frame at level 19 it is 8.0 MiB (zlib: 10.2 MiB). The frame is made once by
tools/pack-dumpforge.sh and kept in third_party/dump_forge/ with a line of SHA-256 of the UNPACKED program (<name>.elf.sha256: the checksum the
project's own release names in SHA256SUMS). Nothing is compressed here: the bytes of the file go into the array as they are.

Writes (symbol = ps5tm_dumpforge_zst):
  const unsigned char <symbol>[]            the frame
  const unsigned long <symbol>_len          its bytes
  const unsigned long <symbol>_raw_len      the size of the program inside (read from the frame header)
  const char          <symbol>_version[]    from the file name ps5-dump-forge-<version>-ps5.elf.zst
  const char          <symbol>_sha256[]     SHA-256 of the unpacked program (from <file>.sha256 beside the frame)
The app unpacks it in memory (ZSTD_decompress) and compares size and SHA-256 before it hands the program to the loader.
"""
import os
import re
import sys

MAGIC = b"\x28\xb5\x2f\xfd"


def frame_content_size(blob):
    """The content size a zstd frame names in its header (RFC 8878 3.1.1.1), or None when it names none."""
    if blob[:4] != MAGIC:
        sys.exit("gen_zstd_blob: kein zstd-Rahmen (beginnt mit %s)" % blob[:4].hex(" "))
    fhd = blob[4]
    fcs_flag = fhd >> 6
    single = (fhd >> 5) & 1
    dict_len = (0, 1, 2, 4)[fhd & 3]
    pos = 5 + (0 if single else 1) + dict_len
    size_len = {0: 1 if single else 0, 1: 2, 2: 4, 3: 8}[fcs_flag]
    if size_len == 0:
        return None
    v = int.from_bytes(blob[pos:pos + size_len], "little")
    return v + 256 if fcs_flag == 1 else v


def main():
    if len(sys.argv) != 4:
        sys.exit("usage: gen_zstd_blob.py <output.c> <file.elf.zst> <symbol>")
    out_path, zst_path, symbol = sys.argv[1], sys.argv[2], sys.argv[3]
    if not os.path.isfile(zst_path):
        sys.exit("gen_zstd_blob: %s nicht gefunden" % zst_path)
    name = os.path.basename(zst_path)
    m = re.fullmatch(r"ps5-dump-forge-(\d+(?:\.\d+)*)-ps5\.elf\.zst", name)
    if not m:
        sys.exit("gen_zstd_blob: der Name %s passt nicht zu ps5-dump-forge-<Version>-ps5.elf.zst" % name)
    version = m.group(1)
    sha_path = zst_path[:-len(".zst")] + ".sha256"
    if not os.path.isfile(sha_path):
        sys.exit("gen_zstd_blob: %s fehlt (SHA-256 des entpackten Programms)" % sha_path)
    sha = open(sha_path, encoding="utf-8").read().split()[0].lower()
    if not re.fullmatch(r"[0-9a-f]{64}", sha):
        sys.exit("gen_zstd_blob: in %s steht keine SHA-256" % sha_path)
    with open(zst_path, "rb") as handle:
        blob = handle.read()
    raw_len = frame_content_size(blob)
    if not raw_len or not (1 << 20) <= raw_len <= (40 << 20):
        sys.exit("gen_zstd_blob: die Größe im Rahmen (%s) ist unglaubwürdig; mit der Datei als Eingabe packen (zstd -19 <Datei>), nicht über eine Pipe" % raw_len)
    os.makedirs(os.path.dirname(out_path) or ".", exist_ok=True)
    with open(out_path, "w", encoding="utf-8", newline="\n") as out:
        out.write("/* Generated by tools/gen_zstd_blob.py - do not edit. */\n\n")
        out.write("const unsigned char %s[] = {\n" % symbol)
        line = ""
        for b in blob:
            piece = "%d," % b
            if len(line) + len(piece) > 118:
                out.write(line + "\n")
                line = ""
            line += piece
        out.write(line + "\n};\n")
        out.write("const unsigned long %s_len = %d;\n" % (symbol, len(blob)))
        out.write("const unsigned long %s_raw_len = %d;\n" % (symbol, raw_len))
        out.write('const char %s_version[] = "%s";\n' % (symbol, version))
        out.write('const char %s_sha256[] = "%s";\n' % (symbol, sha))
    print("gen_zstd_blob: %s eingebettet (%d KiB gepackt, %d KiB entpackt, Version %s) -> %s" % (name, len(blob) // 1024, raw_len // 1024, version, out_path))


if __name__ == "__main__":
    main()
