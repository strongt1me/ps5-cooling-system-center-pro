#!/usr/bin/env python3
"""Embeds the tested LZ4 profiles of third_party/lz4_profiles into a C source file (15.10.2026).

Usage: gen_lz4_profiles.py <output.c> <folder>

The folder holds the TOML profiles and index.json, both as LZ4 Compression 1.5.0 ships them (profiles/, GPL-3.0): for each
profile its file, a label, the game it was tested on, where it was posted, and what picks it for a game (Title IDs, words of
the name, the engine by the file layout). The profiles were written and tested by danthespal and posted with MkPFS.CSharp
(GPL-3.0); they are embedded unchanged, as text, with their SHA-256. src/imgjob_lz4.inc offers them in the LZ4 window and
picks one for a game (table ps5tm_lz4profs).

A profile that names lists beside it (include_from / exclude_from) cannot be built in: the app reads built-in profiles from
memory, where there is nothing beside them. Such a file, a missing one or a bad entry stops the build.
"""
import hashlib
import json
import os
import re
import sys


def c_str(b):
    """bytes as C string literal pieces, one per line of the file"""
    out = []
    for line in b.decode("utf-8").splitlines(keepends=True):
        s = line.replace("\\", "\\\\").replace('"', '\\"').replace("\t", "\\t").replace("\r", "\\r").replace("\n", "\\n")
        s = re.sub(r"\?\?", "?\\\\?", s)                    # no trigraphs
        out.append('    "%s"' % s)
    return "\n".join(out) if out else '    ""'


def main():
    if len(sys.argv) != 3:
        sys.exit("usage: gen_lz4_profiles.py <output.c> <folder>")
    out_path, folder = sys.argv[1], sys.argv[2]
    index = json.load(open(os.path.join(folder, "index.json"), encoding="utf-8"))
    rows = []
    for e in index:
        for k in ("id", "file", "label", "tested", "source"):
            if not isinstance(e.get(k), str) or not e[k]:
                sys.exit("index.json: %r ohne %s" % (e.get("id"), k))
        if not re.fullmatch(r"[a-z0-9-]+", e["id"]) or not re.fullmatch(r"[A-Za-z0-9._-]+\.toml", e["file"]):
            sys.exit("index.json: unpassende id oder Datei: %r" % e)
        data = open(os.path.join(folder, e["file"]), "rb").read()
        text = data.decode("utf-8")
        if re.search(r"^\s*(include_from|exclude_from)\s*=", text, re.M):
            sys.exit("%s nennt Listen neben sich (include_from / exclude_from): so nicht einbettbar" % e["file"])
        ids = [x.upper() for x in e.get("titleIds", [])]
        names = [x.lower() for x in e.get("names", [])]
        if any(not re.fullmatch(r"[A-Z]{4}\d{5}", x) for x in ids) or any(not re.fullmatch(r"[a-z0-9]{4,}", x) for x in names):
            sys.exit("index.json: Titel-ID oder Name in falscher Form: %r" % e)
        engine = e.get("engine", "")
        if engine not in ("", "insomniac", "unity"):
            sys.exit("index.json: unbekannte Engine %r" % engine)
        rows.append((e, data, ",".join(ids), ",".join(names), engine, hashlib.sha256(data).hexdigest()))

    def q(s):
        return '"%s"' % s.replace("\\", "\\\\").replace('"', '\\"')

    with open(out_path, "w", encoding="utf-8", newline="\n") as f:
        f.write("/* Generated by tools/gen_lz4_profiles.py from third_party/lz4_profiles. Do not edit. */\n")
        f.write('#include "ps5tm.h"\n\n')
        for i, (e, data, *_rest) in enumerate(rows):
            f.write("static const char text_%d[] =\n%s;\n\n" % (i, c_str(data)))
        f.write("const ps5tm_lz4prof_t ps5tm_lz4profs[] = {\n")
        for i, (e, data, ids, names, engine, sha) in enumerate(rows):
            f.write("  { %s, %s, %s, %s, %s,\n    %s, %s, %s, text_%d, %d, %s },\n" % (
                q(e["id"]), q(e["file"]), q(e["label"]), q(e["tested"]), q(e["source"]), q(ids), q(names), q(engine), i, len(data), q(sha)))
        f.write("};\nconst unsigned ps5tm_lz4prof_count = %d;\n" % len(rows))
    print("%s: %d Profile, %d Bytes" % (out_path, len(rows), sum(len(r[1]) for r in rows)))


if __name__ == "__main__":
    main()
